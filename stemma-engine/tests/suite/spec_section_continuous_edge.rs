/// ISO 29500-1 section 17.6.22: sections around a nextPage break.
///
/// S1(nextPage, 1440 margins) -> S2(continuous, no margins) ->
/// S3(nextPage, 2880 margins, landscape) -> S4(continuous, no margins)
///
/// S2 keeps its margins omitted.
#[test]
fn spec_non_continuous_s2_keeps_its_omissions() {
    let (_rt, doc) = common::import_fixture(FIXTURES, "non-continuous-breaks-chain");

    let section_props = section_paragraphs(&doc);
    assert_eq!(
        section_props.len(),
        3,
        "should have 3 mid-document sections (S1, S2, S3), got {}",
        section_props.len()
    );

    // S2 (continuous) should inherit margins from S1 (1440)
    let s2 = section_props[1];
    assert_eq!(
        s2.section_type,
        Some(stemma::domain::SectionType::Continuous),
        "S2 should be continuous"
    );
    assert_eq!(
        s2.margin_top, None,
        "S2 margin_top is not authored, so it stays omitted (Word reads its own default), got {:?}",
        s2.margin_top
    );
    assert_eq!(
        s2.margin_left, None,
        "S2 margin_left is not authored, so it stays omitted (Word reads its own default), got {:?}",
        s2.margin_left
    );
}

/// S3 (nextPage) keeps its own margins and does NOT inherit.
#[test]
fn spec_non_continuous_s3_keeps_own_values() {
    let (_rt, doc) = common::import_fixture(FIXTURES, "non-continuous-breaks-chain");

    let section_props = section_paragraphs(&doc);
    let s3 = section_props[2];

    assert_eq!(
        s3.section_type,
        Some(stemma::domain::SectionType::NextPage),
        "S3 should be nextPage"
    );
    assert_eq!(
        s3.margin_top,
        Some(2880),
        "S3 margin_top should be 2880 (own), got {:?}",
        s3.margin_top
    );
    assert_eq!(
        s3.margin_left,
        Some(2880),
        "S3 margin_left should be 2880 (own), got {:?}",
        s3.margin_left
    );
    assert_eq!(
        s3.page_width,
        Some(15840),
        "S3 page_width should be 15840 (landscape), got {:?}",
        s3.page_width
    );
    assert_eq!(
        s3.page_height,
        Some(12240),
        "S3 page_height should be 12240 (landscape), got {:?}",
        s3.page_height
    );
    assert_eq!(
        s3.orientation,
        Some(stemma::domain::PageOrientation::Landscape),
        "S3 orientation should be Landscape, got {:?}",
        s3.orientation
    );
}

/// S4 (continuous, body-level) keeps its margins omitted too: S3's 2880
/// margins and landscape page are not copied in.
#[test]
fn spec_non_continuous_s4_keeps_its_omissions() {
    let (_rt, doc) = common::import_fixture(FIXTURES, "non-continuous-breaks-chain");

    let body_sp = doc
        .body_section_properties
        .as_ref()
        .expect("body_section_properties should exist (S4)");

    assert_eq!(
        body_sp.section_type,
        Some(stemma::domain::SectionType::Continuous),
        "S4 should be continuous"
    );

    // S4 inherits from S3 (2880 margins), NOT S1 (1440) or S2 (inherited 1440)
    assert_eq!(
        body_sp.margin_top, None,
        "S4 margin_top is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.margin_top
    );
    assert_eq!(
        body_sp.margin_left, None,
        "S4 margin_left is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.margin_left
    );
    assert_eq!(
        body_sp.margin_bottom, None,
        "S4 margin_bottom is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.margin_bottom
    );
    assert_eq!(
        body_sp.margin_right, None,
        "S4 margin_right is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.margin_right
    );

    // S4 inherits page size and orientation from S3 (landscape)
    assert_eq!(
        body_sp.page_width, None,
        "S4 page_width is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.page_width
    );
    assert_eq!(
        body_sp.page_height, None,
        "S4 page_height is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.page_height
    );
    assert_eq!(
        body_sp.orientation, None,
        "S4 orientation is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.orientation
    );

    // S4 inherits gutter from S3
    assert_eq!(
        body_sp.gutter, None,
        "S4 gutter is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.gutter
    );

    // S4 inherits header/footer distances from S3
    assert_eq!(
        body_sp.header_distance, None,
        "S4 header_distance is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.header_distance
    );
    assert_eq!(
        body_sp.footer_distance, None,
        "S4 footer_distance is not authored, so it stays omitted (Word reads its own default), got {:?}",
        body_sp.footer_distance
    );
}

